// FixtureHistory.swift
// GroveKitTests
//
// Plans a branchy history and writes it as a `git fast-import` stream, which builds 10k commits in seconds.

import Foundation

struct FixtureSubmoduleLink {
    let path: String
    let url: String
    let sha: String
}

final class FixtureHistory {

    struct Feature {
        let name: String
        let length: Int
        let willMerge: Bool
        let openStep: Int
        var baseFiles: [String: FileVersion] = [:]
        var overrides: [String: FileVersion] = [:]
        var tip = 0
        var commits = 0
        var merged = false
        var lastDate = 0
    }

    struct FileVersion {
        let mark: Int
        let lines: [String]
    }

    private(set) var features: [Feature] = []
    private(set) var mainMarks: [(mark: Int, date: Int)] = []
    private(set) var commitCount = 0

    private let spec: FixtureSpec
    private var rng: FixtureRandom
    private let out: FixtureStreamWriter
    private var nextMark = 1
    private var date: Int
    private let meanGap: Int
    private var mainFiles: [String: FileVersion] = [:]
    private var mainPaths: [String] = []
    private var mainTip = 0
    private var lineCounter = 0

    init(spec: FixtureSpec, out: FixtureStreamWriter) {
        self.spec = spec
        self.out = out
        rng = FixtureRandom(seed: spec.seed)
        meanGap = 5_400
        date = Int(spec.endDate.timeIntervalSince1970) - spec.commits * meanGap
    }

    /// Writes the whole history: main, feature branches (some merged, some abandoned), tags.
    func write(featureCount: Int, submodules: [FixtureSubmoduleLink]) {
        planFeatures(count: featureCount)
        writeInitialCommit()
        let mainSteps = max(1, mainStepBudget())
        let featureShare = Double(features.reduce(0) { $0 + $1.length }) / Double(max(1, spec.commits))
        let submoduleStep = mainSteps / 3
        var step = 0, nextToOpen = 0
        var active: [Int] = []
        while commitCount < spec.commits {
            while nextToOpen < features.count, features[nextToOpen].openStep <= step {
                open(nextToOpen)
                active.append(nextToOpen)
                nextToOpen += 1
            }
            if !active.isEmpty, rng.chance(featureShare) {
                let slot = rng.int(active.count)
                let index = active[slot]
                commitOnFeature(index)
                if features[index].commits >= features[index].length {
                    active.remove(at: slot)
                    if features[index].willMerge { merge(index) }
                }
            } else {
                if step == submoduleStep, !submodules.isEmpty {
                    commitSubmodules(submodules)
                } else {
                    commitOnMain()
                }
                step += 1
            }
        }
        // Branch counts are part of the spec, so late features still get a commit.
        for index in nextToOpen..<features.count {
            open(index)
            commitOnFeature(index)
        }
        if step <= submoduleStep, !submodules.isEmpty { commitSubmodules(submodules) }
        writeTags()
    }

    // MARK: - Planning

    private func mainStepBudget() -> Int {
        let featureCommits = features.reduce(0) { $0 + $1.length }
        let merges = features.filter(\.willMerge).count
        return spec.commits - featureCommits - merges - 1
    }

    private func planFeatures(count: Int) {
        guard count > 0 else { return }
        // Feature work is at most ~45% of history; the rest lands on main directly.
        let average = max(1, min(6, Int(Double(spec.commits) * 0.45) / count))
        let lengths = (0..<count).map { _ in 1 + rng.int(2 * average - 1) }
        let merges = Int(Double(count) * 0.7)
        let mainSteps = max(count, spec.commits - lengths.reduce(0, +) - merges - 1)
        features = (0..<count).map { index in
            let open = min(mainSteps - 1, index * mainSteps / count + rng.int(max(1, mainSteps / count)))
            return Feature(name: FixtureVocabulary.branchName(index, &rng), length: lengths[index],
                           willMerge: rng.chance(0.7), openStep: open)
        }
        features.sort { $0.openStep < $1.openStep }
    }

    // MARK: - Commits

    private func writeInitialCommit() {
        var changes: [(String, Int)] = []
        for index in 0..<spec.files {
            let path = FixtureVocabulary.filePath(index, &rng)
            let lines = (0..<rng.int(in: 12...70)).map { _ in newLine() }
            let version = blob(lines)
            mainFiles[path] = version
            mainPaths.append(path)
            changes.append((path, version.mark))
        }
        let readme = blob(["# Fixture", "", "Generated by tools/fixtures. Seed \(spec.seed)."])
        mainFiles["README.md"] = readme
        mainPaths.append("README.md")
        changes.append(("README.md", readme.mark))
        mainTip = commit(ref: "refs/heads/main", message: "chore: initial commit", parents: [], changes: changes)
        mainMarks.append((mainTip, date))
    }

    private func commitOnMain() {
        var changes: [(String, Int)] = []
        for path in pickPaths(from: mainPaths) {
            let version = mutate(mainFiles[path]!)
            mainFiles[path] = version
            changes.append((path, version.mark))
        }
        if rng.chance(0.04) {
            let path = FixtureVocabulary.filePath(spec.files + mainPaths.count, &rng)
            let version = blob((0..<rng.int(in: 8...40)).map { _ in newLine() })
            mainFiles[path] = version
            mainPaths.append(path)
            changes.append((path, version.mark))
        }
        mainTip = commit(ref: "refs/heads/main", message: message(), parents: [mainTip], changes: changes)
        mainMarks.append((mainTip, date))
    }

    private func open(_ index: Int) {
        features[index].baseFiles = mainFiles
        features[index].tip = mainTip
    }

    private func commitOnFeature(_ index: Int) {
        var feature = features[index]
        var changes: [(String, Int)] = []
        for path in pickPaths(from: mainPaths) {
            guard let current = feature.overrides[path] ?? feature.baseFiles[path] else { continue }
            let version = mutate(current)
            feature.overrides[path] = version
            changes.append((path, version.mark))
        }
        feature.tip = commit(ref: "refs/heads/\(feature.name)", message: message(), parents: [feature.tip], changes: changes)
        feature.commits += 1
        feature.lastDate = date
        features[index] = feature
    }

    /// The merge keeps main's tree and takes the feature's version of every file it touched.
    private func merge(_ index: Int) {
        let feature = features[index]
        var changes: [(String, Int)] = []
        for (path, version) in feature.overrides.sorted(by: { $0.key < $1.key }) {
            mainFiles[path] = version
            changes.append((path, version.mark))
        }
        let subject = rng.chance(0.8)
            ? "Merge pull request #\(2_000 + index) from example/\(feature.name)"
            : "Merge branch '\(feature.name)'"
        mainTip = commit(ref: "refs/heads/main", message: subject, parents: [mainTip, feature.tip], changes: changes)
        mainMarks.append((mainTip, date))
        features[index].merged = true
        features[index].baseFiles = [:]
        features[index].overrides = [:]
    }

    private func commitSubmodules(_ links: [FixtureSubmoduleLink]) {
        let config = links.flatMap { ["[submodule \"\($0.path)\"]", "\tpath = \($0.path)", "\turl = \($0.url)"] }
        let gitmodules = blob(config)
        var lines = ["M 100644 :\(gitmodules.mark) .gitmodules"]
        lines += links.map { "M 160000 \($0.sha) \($0.path)" }
        mainTip = commit(ref: "refs/heads/main", message: "chore(deps): add shared submodules",
                         parents: [mainTip], changes: [], rawChanges: lines)
        mainMarks.append((mainTip, date))
    }

    // MARK: - Tags

    private func writeTags() {
        guard spec.tags > 0 else { return }
        var major = 1, minor = 0, patch = 0
        for index in 0..<spec.tags {
            let target = mainMarks[min(mainMarks.count - 1, index * mainMarks.count / spec.tags)]
            if index % 10 < 7 {
                patch += 1
                if rng.chance(0.15) { minor += 1; patch = 0 }
                if rng.chance(0.02) { major += 1; minor = 0; patch = 0 }
                let author = FixtureVocabulary.author(rng.skewedIndex(spec.authors))
                let message = "Release \(major).\(minor).\(patch)\n"
                out.line("tag v\(major).\(minor).\(patch)")
                out.line("from :\(target.mark)")
                out.line("tagger \(author.name) <\(author.email)> \(target.date + 60) +0000")
                out.data(message)
            } else {
                out.line("reset refs/tags/build/\(10_000 + index)")
                out.line("from :\(target.mark)")
                out.line("")
            }
        }
    }

    // MARK: - Primitives

    private func commit(ref: String, message: String, parents: [Int], changes: [(String, Int)],
                        rawChanges: [String] = []) -> Int {
        date += 60 + rng.int(2 * meanGap)
        let mark = nextMark
        nextMark += 1
        let author = FixtureVocabulary.author(rng.skewedIndex(spec.authors))
        out.line("commit \(ref)")
        out.line("mark :\(mark)")
        out.line("author \(author.name) <\(author.email)> \(date) +0000")
        out.line("committer \(author.name) <\(author.email)> \(date) +0000")
        out.data(message)
        if let first = parents.first { out.line("from :\(first)") }
        for parent in parents.dropFirst() { out.line("merge :\(parent)") }
        for (path, blobMark) in changes { out.line("M 100644 :\(blobMark) \(path)") }
        for line in rawChanges { out.line(line) }
        out.line("")
        commitCount += 1
        return mark
    }

    private func blob(_ lines: [String]) -> FileVersion {
        let mark = nextMark
        nextMark += 1
        out.line("blob")
        out.line("mark :\(mark)")
        out.data(lines.joined(separator: "\n") + "\n")
        return FileVersion(mark: mark, lines: lines)
    }

    /// Small edits (replace, insert, delete a line or two) so commit diffs look like real ones.
    private func mutate(_ version: FileVersion) -> FileVersion {
        var lines = version.lines
        for _ in 0..<rng.int(in: 1...3) {
            let position = rng.int(max(1, lines.count))
            switch rng.int(4) {
            case 0 where lines.count > 4: lines.remove(at: position)
            case 1: lines.insert(newLine(), at: position)
            default:
                if lines.isEmpty { lines.append(newLine()) } else { lines[position] = newLine() }
            }
        }
        return blob(lines)
    }

    private func pickPaths(from paths: [String]) -> [String] {
        let count = rng.chance(0.1) ? rng.int(in: 4...12) : rng.int(in: 1...3)
        return Array(Set((0..<count).map { _ in paths[rng.skewedIndex(paths.count)] })).sorted()
    }

    private func message() -> String {
        FixtureVocabulary.subject(&rng) + FixtureVocabulary.body(&rng)
    }

    private func newLine() -> String {
        lineCounter += 1
        return FixtureVocabulary.codeLine(&rng, lineCounter)
    }
}

/// Buffered writer for the fast-import stream; `data` handles the byte-counted payload syntax.
final class FixtureStreamWriter {
    private let handle: FileHandle
    private var buffer = Data()

    init(url: URL) throws {
        FileManager.default.createFile(atPath: url.path, contents: nil)
        handle = try FileHandle(forWritingTo: url)
    }

    func line(_ text: String) {
        buffer.append(contentsOf: text.utf8)
        buffer.append(0x0A)
        if buffer.count > 1 << 20 { flush() }
    }

    func data(_ payload: String) {
        let bytes = Array(payload.utf8)
        line("data \(bytes.count)")
        buffer.append(contentsOf: bytes)
        buffer.append(0x0A)
    }

    func close() {
        flush()
        try? handle.close()
    }

    private func flush() {
        handle.write(buffer)
        buffer.removeAll(keepingCapacity: true)
    }
}
